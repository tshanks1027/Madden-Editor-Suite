// Helper function to get team by ID
export function getTeamById(teamId) {
  return NFL_TEAMS[teamId] || null;
}

// Helper function to get team by name
export function getTeamByName(teamName) {
  return Object.values(NFL_TEAMS).find(
    team => team.name.toLowerCase() === teamName.toLowerCase() ||
            team.fullName.toLowerCase() === teamName.toLowerCase()
  ) || null;
}

// Get all teams as array
export function getAllTeams() {
  return Object.values(NFL_TEAMS).sort((a, b) => a.fullName.localeCompare(b.fullName));
}
